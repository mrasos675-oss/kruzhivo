export function inferNpa(text) {
 const lines=text.split(/\r?\n/).map(line=>line.trim().replace(/^#\s+/, '')).filter(Boolean).slice(0,30);
 const kindIndex=lines.findIndex(line=>/^(постановление|распоряжение|приказ|решение|закон|указ)\s*$/iu.test(line.replace(/\s+/g,'')));
 const rawKind=kindIndex<0?'':lines[kindIndex].replace(/\s+/g,'').toLowerCase();
 const titleStart=lines.findIndex(line=>/^(?:об? |о внесении |утверждение )/iu.test(line));
 const titleLines=[];
 if(titleStart>=0) for(const line of lines.slice(titleStart,titleStart+8)){
  if(/^(?:\d+[.)]|в соответствии|в целях|руководствуясь|на основании|приказываю|постановляю|решил[аи]?(?:\s|:|$)|приложение|утвержден[оа]?|(?:г|п|с)\.\s|№)/iu.test(line))break;
  titleLines.push(line);
 }
 const title=titleLines.join(' ').replace(/\s+/g,' ');
 const header=lines.slice(0,titleStart>=0?titleStart:12).join(' ');
 const municipalityMatch=header.match(/([\p{L}-]+)\s+(муниципальн(?:ый округ|ого округа|ый район|ого района)|городск(?:ой округ|ого округа)|сельск(?:ое поселение|ого поселения))/iu);
 const capitalize=value=>value.slice(0,1).toUpperCase()+value.slice(1).toLowerCase();
 const cases={'муниципального округа':'муниципальный округ','муниципального района':'муниципальный район','городского округа':'городской округ','сельского поселения':'сельское поселение'};
 const unit=municipalityMatch?.[2].toLowerCase();
 let locality=municipalityMatch?.[1]||'';
 if(cases[unit])locality=locality.replace(/ского$/iu,'ский').replace(/цкого$/iu,'цкий').replace(/ного$/iu,'ный');
 const municipality=locality?capitalize(locality)+' '+(cases[unit]||unit):'';
 const normalized=value=>value.toLowerCase().replaceAll('ё','е');
 const comparable=value=>normalized(value).replace(/ская область$/,'ской област').replace(/цкий автономный округ$/,'цкого автономного округа');
 const matches=regions.filter(region=>{
  const source=normalized(header);
  const name=normalized(region),declined=comparable(region);
  return new RegExp('(?:^|[^\\p{L}])'+name.replace(/[()]/g,'\\$&')+'(?=$|[^\\p{L}])','u').test(source)||(declined!==name&&source.includes(declined));
 });
 const region=matches.length===1?matches[0]:'';
 const level=municipality||/муниципальн/iu.test(header)?'Муниципальный':/правительств[оа] российской федерации|президент российской федерации/iu.test(header)?'Федеральный':region&&/правительств|губернатор|законодательн/iu.test(header)?'Региональный':'';
 const kind=({постановление:'Постановление',распоряжение:'Распоряжение',решение:'Решение',приказ:'Приказ',закон:'Закон',указ:'Указ'})[rawKind]||'';
 return {title,kind,level,region,municipality};
}
