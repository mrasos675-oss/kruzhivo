export function demoAnalysis(text) {
  if (text !== SAMPLE_TEXT && text !== CLEAN_TEXT) throw Object.assign(new Error('Для произвольного документа выберите режим API. Деморежим содержит только два подготовленных примера.'), { status: 422 });
  const findings = text === CLEAN_TEXT ? [] : [
    { id: 'finding-1', factorId: 'F01', point: '2.4', quote: 'Сотрудник вправе запросить иные документы по своему усмотрению.', explanation: 'Перечень дополнительных документов и условия запроса не ограничены в выбранном пункте.', basis: [] },
    { id: 'finding-2', factorId: 'F01', point: '2.5', quote: 'Решение принимается в разумный срок после поступления документов.', explanation: 'Изолированное чтение пункта не позволяет определить продолжительность срока.', basis: [] },
    { id: 'finding-3', factorId: 'F12', point: '3.2', quote: 'В предоставлении услуги может быть отказано при наличии иных обстоятельств.', explanation: 'Оценочная формулировка не раскрывает обстоятельства отказа.', basis: [] },
  ];
  return {
    findings,
    coverage: CATALOG.factors.map(f => ({ factorId: f.id, status: findings.some(x => x.factorId === f.id) ? 'finding' : 'limited', note: 'Подготовленный пример, а не результат полного анализа моделью.' })),
    limitations: ['Демонстрационные ответы подготовлены заранее. Проверка актуальности внешних норм не выполнялась.', CATALOG.note],
  };
}

export function demoReview(findings) {
  return findings.map(f => ({
    findingId: f.id,
    verdict: f.id === 'finding-2' ? 'contested' : 'supported',
    explanation: f.id === 'finding-2' ? 'Пункт 2.6 уточняет срок из пункта 2.5: не более 10 рабочих дней. Это существенное возражение против первоначальной находки.' : 'В представленном фрагменте уточнение не обнаружено. Применимость специальных исключений и действующих норм требует проверки специалистом.',
    counterarguments: f.id === 'finding-2' ? ['Срок конкретизирован в следующем пункте.'] : ['В специальном законодательстве может существовать допустимое исключение.'],
    evidence: f.id === 'finding-2' ? ['Срок, указанный в пункте 2.5, не может превышать 10 рабочих дней со дня регистрации заявления.'] : [],
    checks: { context: f.id === 'finding-2' ? 'Найдено уточнение в п. 2.6' : 'В представленном тексте уточнение не найдено', exception: 'Применимые исключения не установлены', applicability: 'Внешние источники не предоставлены', freshness: 'Актуальность норм не проверена' },
    doubts: ['Правовые основания не заполнены. Оценка ИИ не является решением специалиста.'],
  }));
}

export function demoEdit(findings) {
  return findings.filter(f => f.review?.verdict === 'supported').map(f => ({
    findingId: f.id,
    explanation: f.explanation,
    proposal: f.id === 'finding-1' ? 'Дополнительные документы запрашиваются только в случаях и пределах, прямо предусмотренных применимым законодательством.' : 'Основания отказа должны быть перечислены исчерпывающе. Конкретный перечень необходимо определить по применимым нормам.',
    meaning: 'uncertain',
    meaningExplanation: 'Проект ограничивает усмотрение или требует конкретизации. Без проверки полномочий и применимых норм сохранение смысла подтвердить нельзя.',
  }));
}
